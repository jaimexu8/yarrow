"""Golden replay test for the direct-only OCR gateway.

This test proves that replacing paddleocr-vl-api with direct VLM calls kept the
observable /layout-parsing output byte-for-byte stable on the captured corpus.
It feeds the recorded ort-structure payload back through the gateway, replays
each recorded VLM answer, and compares the normalized result with the golden
file that was captured from the paddlex pipeline.

The crop-to-content mapping uses the gateway's own ``_crop_to_b64_jpeg`` with
the default ``VLM_JPEG_QUALITY`` of 75, applied to every recorded structure
block. The resulting base64 JPEG is the exact string the gateway puts in the
chat request's image_url data URI, so a chat completion can be mapped back to
the expected block_content by looking up that string. If two blocks produced
the same crop but different content, the map would be ambiguous. In that case
the handler falls back to the prompt label ("OCR:", "Table Recognition:", or
"Formula Recognition:") plus the submission order produced by
``_prepare_blocks_sync``. No current golden entry is ambiguous, and the number
of served requests is asserted, so an unexpected request cannot pass silently.

The test cannot prove anything about live model behavior because every VLM
answer is replayed from the golden file. It also cannot exercise OTSL
conversion: the capture stored the final HTML table text, not the raw OTSL the
model emitted, so the gateway's ``_normalize_direct_table_content`` sees HTML
and leaves it alone. Property tests cover OTSL conversion. Two scan_dark text
differences observed in a live shadow run were accepted by the owner because
that page is a scan-quality warning fixture, not a correctness baseline.

Figure digests are compared strictly when the recorded bytes can be
regenerated by the gateway's own ``_extract_figure``. If a future golden has
figures and the JPEG encoder differs between capture and test images, the test
drops only the ``markdown_images_sha256`` comparison and still checks the image
count and keys. All 16 captured entries have no figure blocks, so the strict
comparison currently applies to every entry.
"""

from __future__ import annotations

import base64
import copy
import hashlib
import importlib.util
import json
import re
from collections import Counter, defaultdict
from pathlib import Path
from typing import Any

import httpx
import pytest
from fastapi.testclient import TestClient

try:
    import pymupdf as fitz  # type: ignore[import-not-found]
except ImportError:
    try:
        import fitz  # type: ignore[import-not-found,no-redef]
    except ImportError:
        fitz = None

REPO_ROOT = Path(__file__).resolve().parents[2]
GATEWAY = REPO_ROOT / "ocr_cluster" / "shared" / "hybrid_gateway.py"
GOLDEN_DIR = Path(__file__).parent / "golden" / "gateway"
DOC_DIR = REPO_ROOT / "worker" / "tests" / "integration" / "test_docs"

VLM_JPEG_QUALITY = 75
PDF_ZOOM = 2.0
BLOCK_FIELDS = (
    "block_label",
    "block_bbox",
    "block_content",
    "block_order",
    "block_id",
    "block_image",
)
PROMPT_BY_TEXT = {
    "OCR:": "ocr",
    "Table Recognition:": "table",
    "Formula Recognition:": "formula",
}
DATA_URI_RE = re.compile(r"^data:[A-Za-z0-9+./-]*;base64,", re.IGNORECASE)
BARE_BASE64_RE = re.compile(r"^[A-Za-z0-9+/=\s]+$")
FIGURE_REF_RE = re.compile(
    r"imgs/img_in_image_box_(-?\d+)_(-?\d+)_(-?\d+)_(-?\d+)\.jpg"
)


def _load_gateway():
    spec = importlib.util.spec_from_file_location("hybrid_gateway_golden", GATEWAY)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


@pytest.fixture
def gateway(monkeypatch):
    monkeypatch.setenv("MODEL_NAME", "PP-StructureV3+PaddleOCR-VL")
    monkeypatch.setenv("MODEL_VERSION", "3.2.0+vl-0.9b")
    monkeypatch.setenv("VLM_JPEG_QUALITY", str(VLM_JPEG_QUALITY))
    monkeypatch.delenv("VLM_PIXEL_BUDGETS", raising=False)
    module = _load_gateway()
    assert module.VLM_JPEG_QUALITY == VLM_JPEG_QUALITY
    return module


def _sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _data_uri_digest(value: str) -> str:
    payload = value.partition(",")[2] or value
    try:
        return _sha256(base64.b64decode(payload))
    except (ValueError, TypeError):
        return _sha256(value.encode("utf-8"))


def _is_base64_payload(value: str) -> bool:
    if len(value) < 200:
        return False
    return bool(DATA_URI_RE.match(value) or BARE_BASE64_RE.match(value))


def _scrub(value: Any) -> Any:
    if isinstance(value, dict):
        return {key: _scrub(item) for key, item in value.items()}
    if isinstance(value, list):
        return [_scrub(item) for item in value]
    if isinstance(value, str) and _is_base64_payload(value):
        return "sha256:" + _data_uri_digest(value)
    return value


def _rasterize_first_page(pdf_path: Path, zoom: float) -> bytes:
    with fitz.open(pdf_path) as document:
        pixmap = document[0].get_pixmap(matrix=fitz.Matrix(zoom, zoom), alpha=False)
        return pixmap.tobytes("png")


def _input_bytes(golden: dict) -> bytes:
    path = DOC_DIR / golden["file"]
    if golden["kind"] == "image":
        data = path.read_bytes()
    elif golden["kind"] == "pdf_first_page":
        if fitz is None:
            pytest.skip(
                "PyMuPDF is unavailable in this image; cannot rasterize the "
                "PDF first page that was submitted at capture time"
            )
        data = _rasterize_first_page(path, PDF_ZOOM)
    else:
        raise AssertionError(f"unknown golden kind: {golden['kind']}")
    assert len(data) == golden["bytes"], (
        f"input size mismatch for {golden['file']}: {len(data)} != {golden['bytes']}"
    )
    assert _sha256(data) == golden["sha256"], (
        f"input digest mismatch for {golden['file']}: "
        f"regenerating the capture bytes changed the page"
    )
    return data


def _structure_body(recorded: dict) -> dict:
    return {
        "result": {"layoutParsingResults": [{"prunedResult": copy.deepcopy(recorded)}]}
    }


def _chat(text: str) -> httpx.Response:
    return httpx.Response(
        200,
        json={
            "choices": [
                {
                    "message": {"role": "assistant", "content": text},
                    "finish_reason": "stop",
                }
            ]
        },
    )


def _figure_digests_reproducible(gateway, image, golden: dict) -> bool:
    digests = golden["expected"]["markdown"]["markdown_images_sha256"]
    for key, digest in digests.items():
        match = FIGURE_REF_RE.fullmatch(key)
        if match is None:
            return False
        figure = gateway._extract_figure(image, tuple(int(v) for v in match.groups()))
        if figure is None or figure[0] != key:
            return False
        if _data_uri_digest(figure[1]) != digest:
            return False
    return True


def _normalize(page: dict) -> dict:
    pruned = page["prunedResult"]
    markdown = page.get("markdown") or {}
    images = markdown.get("markdown_images") or {}
    keys = sorted(images)
    return {
        "width": pruned.get("width"),
        "height": pruned.get("height"),
        "blocks": [
            {key: _scrub(block[key]) for key in BLOCK_FIELDS if key in block}
            for block in pruned.get("parsing_res_list", [])
        ],
        "table_res_list": _scrub(pruned.get("table_res_list", [])),
        "markdown": {
            "text": markdown.get("text", ""),
            "markdown_images_count": len(keys),
            "markdown_images_keys": keys,
            "markdown_images_sha256": {
                key: _data_uri_digest(images[key]) for key in keys
            },
        },
    }


def _golden_files():
    return sorted(GOLDEN_DIR.glob("*.json"), key=lambda path: path.name)


@pytest.mark.parametrize("golden_path", _golden_files(), ids=lambda path: path.name)
def test_gateway_replays_golden(gateway, golden_path: Path):
    golden = json.loads(golden_path.read_text(encoding="utf-8"))
    page_bytes = _input_bytes(golden)
    file_b64 = base64.b64encode(page_bytes).decode("ascii")
    image = gateway._decode_image(file_b64)

    pruned = golden["recorded_structure"]
    prepared = gateway._prepare_blocks_sync(
        image, gateway._select_blocks(image, pruned)
    )
    content_by_id = {
        block["block_id"]: block["block_content"]
        for block in golden["expected"]["blocks"]
    }
    submissions = []
    for block, prompt_label, crop in prepared:
        submissions.append(
            {
                "crop": crop,
                "prompt": prompt_label,
                "content": content_by_id[block["block_id"]],
            }
        )

    contents_by_crop = defaultdict(set)
    for submission in submissions:
        contents_by_crop[submission["crop"]].add(submission["content"])
    ambiguous_crops = {
        crop for crop, contents in contents_by_crop.items() if len(contents) > 1
    }

    structure_calls = 0
    model_calls = 0
    served = []
    unmatched = []
    order_by_prompt = defaultdict(int)

    def handler(request: httpx.Request) -> httpx.Response:
        nonlocal structure_calls, model_calls
        path = request.url.path
        if request.method == "POST" and path.endswith("/layout-parsing"):
            structure_calls += 1
            return httpx.Response(200, json=_structure_body(pruned))
        if request.method == "GET" and path.endswith("/models"):
            model_calls += 1
            return httpx.Response(200, json={"data": [{"id": "golden-vlm"}]})
        if request.method == "POST" and path.endswith("/chat/completions"):
            parts = json.loads(request.content)["messages"][0]["content"]
            url = parts[0]["image_url"]["url"]
            crop = url.partition(",")[2]
            prompt = PROMPT_BY_TEXT.get(parts[1]["text"])
            if prompt is None:
                unmatched.append(("prompt", parts[1]["text"]))
                return _chat("")
            if crop in contents_by_crop and crop not in ambiguous_crops:
                content = next(iter(contents_by_crop[crop]))
            else:
                candidates = [s for s in submissions if s["prompt"] == prompt]
                index = order_by_prompt[prompt]
                order_by_prompt[prompt] += 1
                if index >= len(candidates):
                    unmatched.append(("order", prompt, index))
                    return _chat("")
                content = candidates[index]["content"]
            served.append((crop, prompt))
            return _chat(content)
        return httpx.Response(404)

    with TestClient(gateway.app) as client:
        transport_client = httpx.AsyncClient(transport=httpx.MockTransport(handler))
        gateway.app.state.httpx_client = transport_client
        gateway.app.state.vlm_client = gateway._DirectVLMClient(transport_client)
        response = client.post(
            "/layout-parsing", json={"file": file_b64, "fileType": 1}
        )

    assert response.status_code == 200, response.text
    assert structure_calls == 1
    assert model_calls == (1 if submissions else 0)
    assert not unmatched, unmatched
    assert Counter(served) == Counter((s["crop"], s["prompt"]) for s in submissions), (
        "the gateway did not issue exactly the recorded VLM requests"
    )

    page = response.json()["result"]["layoutParsingResults"][0]
    for block in page["prunedResult"].get("parsing_res_list", []):
        assert not block.get("vlm_failed"), block
        assert not block.get("vlm_truncated"), block

    expected = copy.deepcopy(golden["expected"])
    normalized = _normalize(page)
    if not _figure_digests_reproducible(gateway, image, golden):
        expected["markdown"].pop("markdown_images_sha256")
        normalized["markdown"].pop("markdown_images_sha256")
    assert normalized == expected
